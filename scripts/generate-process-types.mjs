import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { join } from "node:path";

const root = process.cwd();
const skillsDir = join(root, "agent", "skills");
const output = join(root, "shared", "generated", "process-types.ts");
const required = ["id", "version", "name", "description", "ownerPolicy", "responsiblePolicy", "deadlinePolicy", "openingCheckpoint", "stages", "completion"];

const entries = await readdir(skillsDir, { withFileTypes: true });
const manifests = [];

for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
  if (!entry.isDirectory()) continue;
  const path = join(skillsDir, entry.name, "process.json");
  let raw;
  try {
    raw = await readFile(path, "utf8");
  } catch (error) {
    if (error && error.code === "ENOENT") continue;
    throw error;
  }

  const manifest = JSON.parse(raw);
  for (const key of required) {
    if (!(key in manifest)) throw new Error(`${path}: missing ${key}`);
  }
  if (manifest.id !== entry.name) {
    throw new Error(`${path}: manifest id must match directory name (${entry.name})`);
  }
  if (!Array.isArray(manifest.stages) || manifest.stages.length === 0) {
    throw new Error(`${path}: stages must be non-empty`);
  }
  manifests.push(manifest);
}

const ids = new Set();
for (const manifest of manifests) {
  if (ids.has(manifest.id)) throw new Error(`Duplicate process type id: ${manifest.id}`);
  ids.add(manifest.id);
}

await mkdir(join(root, "shared", "generated"), { recursive: true });
const source = `import type { ProcessTypeManifest } from "../types/process";\n\n// Generated by scripts/generate-process-types.mjs. Do not edit by hand.\nexport const PROCESS_TYPE_MANIFESTS = ${JSON.stringify(manifests, null, 2)} as const satisfies readonly ProcessTypeManifest[];\n`;
await writeFile(output, source, "utf8");
console.log(`Generated ${manifests.length} process type manifest(s).`);
